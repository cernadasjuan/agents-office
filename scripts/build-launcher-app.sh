#!/bin/bash
# Builds "Agents Office.app": a minimal macOS app bundle whose only job is to exec the
# launcher (scripts/launcher/agents-office-launcher.mjs). No AppleScript, no osacompile, no
# new runtime dependency.
#
# Usage: build-launcher-app.sh <repo-root> <dest-dir>
#   <dest-dir> is the folder that will hold "Agents Office.app" (created if missing).
#
# Called by scripts/install-launcher.sh. Safe to call directly (e.g. to build into a temp
# folder for verification); it only ever writes inside <dest-dir>.
set -euo pipefail

if [ "$#" -ne 2 ]; then
  echo "usage: $0 <repo-root> <dest-dir>" >&2
  exit 1
fi

script_dir="$(cd "$(dirname "$0")" && pwd)"

repo_root="$1"
dest_dir="$2"
app_path="$dest_dir/Agents Office.app"

if [ ! -x "$repo_root/node_modules/.bin/vite" ]; then
  echo "error: $repo_root/node_modules/.bin/vite not found. Run the repo install first (see README)." >&2
  exit 1
fi

mkdir -p "$dest_dir"
rm -rf "$app_path"
mkdir -p "$app_path/Contents/MacOS" "$app_path/Contents/Resources"

# Issue #205: a procedurally generated icon (scripts/launcher/icon.svg, packed into
# scripts/launcher/AgentsOffice.icns by scripts/launcher/generate-icon.mjs — a maintenance
# tool, not run here). Graceful degradation: a checkout missing the .icns (should not happen,
# it is committed) still builds the app, just without an icon, same as before this issue.
icon_src="$script_dir/launcher/AgentsOffice.icns"
icon_plist_entry=""
if [ -f "$icon_src" ]; then
  cp "$icon_src" "$app_path/Contents/Resources/AgentsOffice.icns"
  icon_plist_entry="  <key>CFBundleIconFile</key>
  <string>AgentsOffice</string>
"
fi

cat > "$app_path/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key>
  <string>Agents Office</string>
  <key>CFBundleDisplayName</key>
  <string>Agents Office</string>
  <key>CFBundleIdentifier</key>
  <string>dev.gabrielamyot.agents-office-launcher</string>
  <key>CFBundleVersion</key>
  <string>1</string>
  <key>CFBundleShortVersionString</key>
  <string>1.0</string>
  <key>CFBundlePackageType</key>
  <string>APPL</string>
  <key>CFBundleExecutable</key>
  <string>agents-office-launcher</string>
${icon_plist_entry}  <key>LSUIElement</key>
  <true/>
  <key>LSMinimumSystemVersion</key>
  <string>11.0</string>
</dict>
</plist>
PLIST

launcher_bin="$app_path/Contents/MacOS/agents-office-launcher"
repo_root_file="$app_path/Contents/Resources/repo-root.txt"

# The repo path never goes into the generated shell source below (a path holding a `$`, a
# backtick or a quote would otherwise change what the script runs at launch). printf writes it
# as plain bytes, no shell interpretation either way; the generated script reads it back as
# data at run time and keeps it in a quoted variable from then on.
printf '%s' "$repo_root" > "$repo_root_file"

# This heredoc is fully quoted ('SCRIPT'): nothing below is build-time shell source, it is
# written out byte for byte. The generated script is the same regardless of repo_root.
# find_node itself is not duplicated here: scripts/launcher/find-node.sh is the one source
# (also sourced directly by tests/launcher-build.test.ts), spliced in below.
cat > "$launcher_bin" <<'HEADER'
#!/bin/bash
# Generated by scripts/build-launcher-app.sh. Do not edit by hand; rerun the installer
# (scripts/install-launcher.sh) after a git pull instead.
set -euo pipefail

bin_dir="$(cd "$(dirname "$0")" && pwd)"
repo_root="$(cat "$bin_dir/../Resources/repo-root.txt")"
export AGENTS_OFFICE_REPO_ROOT="$repo_root"

HEADER
cat "$script_dir/launcher/find-node.sh" >> "$launcher_bin"
cat >> "$launcher_bin" <<'FOOTER'

node_bin="$(find_node || true)"
if [ -z "$node_bin" ]; then
  log_dir="$HOME/Library/Logs/agents-office"
  mkdir -p "$log_dir"
  echo "$(date -u +%FT%TZ) launcher failed: node not found on PATH or in known install locations" >> "$log_dir/launcher.log"
  /usr/bin/osascript -e 'display notification "Install Node.js, then try Agents Office again." with title "Agents Office"' >/dev/null 2>&1 || true
  exit 1
fi

export PATH="$(dirname "$node_bin"):$PATH"
exec "$node_bin" "$repo_root/scripts/launcher/agents-office-launcher.mjs"
FOOTER

chmod +x "$launcher_bin"
echo "built: $app_path"
